#!/usr/bin/env python3
"""Format the output of ``cifar10_benchmark.py`` as Table 1 (LaTeX).

Reads ``table_core_ood.json`` and ``table_id_quality.json`` from the benchmark
directory, prints the new numbers next to the ones reported in the paper, and
writes the LaTeX table.

    python experiments/make_table1.py --bench-dir runs/benchmark --output runs/benchmark/table1.tex
"""

import argparse
import json
from pathlib import Path

# Rows of Table 1, in order; the remaining baselines go in the caption.
MAIN_ROWS = [
    ('Softmax+MSP', 'Softmax + MSP'),
    ('Softmax+Energy', 'Softmax + Energy'),
    ('EDL', 'EDL'),
    ('MP-ENN-Yager', 'MP-ENN-Yager'),
    ('MP-ENN-Dempster', 'MP-ENN-Dempster'),
    ('Deep Ensemble', 'Deep Ensemble (5)'),
]
CAPTION_ROWS = ['Softmax+ODIN', 'DUQ', 'SNGP', 'MC Dropout']

# Values reported in Table 1 of the paper (macro over the seven OOD sets).
PAPER = {
    'Softmax+MSP': dict(acc=94.33, ece=.036, auroc=0.653, fpr=0.853),
    'Softmax+Energy': dict(acc=94.33, ece=.036, auroc=0.863, fpr=0.345),
    'EDL': dict(acc=94.04, ece=.050, auroc=0.895, fpr=0.337),
    'MP-ENN-Yager': dict(acc=94.33, ece=.036, auroc=0.860, fpr=0.342),
    'MP-ENN-Dempster': dict(acc=94.26, ece=.042, auroc=0.912, fpr=0.292),
    'Deep Ensemble': dict(acc=94.20, ece=.043, auroc=0.954, fpr=0.164),
    'Softmax+ODIN': dict(auroc=0.871),
    'DUQ': dict(auroc=0.859),
    'SNGP': dict(auroc=0.886),
    'MC Dropout': dict(auroc=0.885),
}


def fmt(mean: float, std: float, dec: int, strip_zero: bool = False) -> str:
    """Paper style: the std drops its leading zero ($94.33{\\pm}.13$); ECE drops it on the mean too."""
    m = f'{mean:.{dec}f}'
    s = f'{std:.{dec}f}'
    s = s[1:] if s.startswith('0.') else s
    if strip_zero and m.startswith('0.'):
        m = m[1:]
    return f'${m}{{\\pm}}{s}$'


def _bold(cell: str) -> str:
    return cell.replace('$', '$\\mathbf{', 1).replace('{\\pm}', '}{\\pm}', 1)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--bench-dir', required=True, help='cifar10_benchmark.py --output-dir')
    p.add_argument('--output', default=None, help='write the LaTeX table here')
    args = p.parse_args()

    bd = Path(args.bench_dir)
    core = json.loads((bd / 'table_core_ood.json').read_text())['methods']
    idq = json.loads((bd / 'table_id_quality.json').read_text())['methods']
    cfg_path = bd / 'run_config.json'
    cfg = json.loads(cfg_path.read_text()) if cfg_path.exists() else {}
    n_seeds, n_epochs = cfg.get('seeds', '?'), cfg.get('epochs', '?')
    ens = cfg.get('ensemble_size', 5)

    print(f'Benchmark: {bd}  (seeds={n_seeds}, epochs={n_epochs}, ensemble={ens})\n')
    print(f"{'method':<17} {'macro AUROC':>16} {'paper':>7} {'delta':>7}   {'ID acc':>7} {'paper':>7}")
    print('-' * 70)
    for key in [k for k, _ in MAIN_ROWS] + CAPTION_ROWS:
        if key not in core:
            print(f'{key:<17} {"missing":>16}')
            continue
        a, asd = core[key]['macro_auroc_mean'], core[key]['macro_auroc_std']
        ref = PAPER.get(key, {})
        acc = idq[key]['accuracy_mean']
        print(f"{key:<17} {a:>10.3f}±{asd:.3f} {ref.get('auroc', float('nan')):>7.3f} "
              f"{a - ref.get('auroc', float('nan')):>+7.3f}   {acc:>7.2f} {ref.get('acc', float('nan')):>7.2f}")

    best_auroc = max(core[k]['macro_auroc_mean'] for k, _ in MAIN_ROWS if k in core)
    best_fpr = min(core[k]['macro_fpr95_mean'] for k, _ in MAIN_ROWS if k in core)
    lines = []
    for key, label in MAIN_ROWS:
        if key not in core:
            continue
        if key == 'Deep Ensemble':
            label = f'Deep Ensemble ({ens})'
        c, q = core[key], idq[key]
        au = fmt(c['macro_auroc_mean'], c['macro_auroc_std'], 3)
        fp = fmt(c['macro_fpr95_mean'], c['macro_fpr95_std'], 3)
        if abs(c['macro_auroc_mean'] - best_auroc) < 1e-12:
            au = _bold(au)
        if abs(c['macro_fpr95_mean'] - best_fpr) < 1e-12:
            fp = _bold(fp)
        lines.append(f"{label:<17} & {fmt(q['accuracy_mean'], q['accuracy_std'], 2)} "
                     f"& {fmt(q['ece_mean'], q['ece_std'], 3, strip_zero=True)} & {au} & {fp} \\\\")

    extra = [f"{k} ${core[k]['macro_auroc_mean']:.3f}$" for k in CAPTION_ROWS if k in core]
    tex = f"""% Generated by experiments/make_table1.py from {bd} (seeds={n_seeds}, epochs={n_epochs})
\\begin{{table}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{4pt}}
\\caption{{{n_seeds}-seed CIFAR-10/OpenOOD comparison; macro AUROC and FPR95
averaged across seven OOD datasets. Further {n_seeds}-seed AUROCs: {', '.join(extra) if extra else 'n/a'}.}}
\\label{{tab:ood_results}}
\\begin{{tabular}}{{@{{}}lcccc@{{}}}}
\\toprule
Method            & ID acc.\\ (\\%)  & ECE             & Macro AUROC          & Macro FPR95 \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    if args.output:
        Path(args.output).write_text(tex)
        print(f'\nwrote {args.output}')
    print('\n' + tex)


if __name__ == '__main__':
    main()
