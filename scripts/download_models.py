#!/usr/bin/env python3
"""Pre-fetch the pretrained weights the experiments load, for offline compute nodes.

  resnet18       torchvision ResNet-18, ImageNet-1k (~45 MB): encoder of every CIFAR-10 model
  roberta-base   Hugging Face roberta-base + tokenizer (~500 MB): ChaosNLI model

Weights are cached under .cache/ in the repository. The script also writes
scripts/env.sh; `source scripts/env.sh` points PyTorch and Hugging Face at that
cache and switches Hugging Face to offline mode.

    python scripts/download_models.py            # everything
    python scripts/download_models.py --check    # verify only
    python scripts/download_models.py --only resnet18
"""

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TORCH_HOME = Path(os.environ.get('TORCH_HOME', ROOT / '.cache' / 'torch'))
HF_HOME = Path(os.environ.get('HF_HOME', ROOT / '.cache' / 'huggingface'))


def get_resnet18(check_only: bool) -> bool:
    os.environ['TORCH_HOME'] = str(TORCH_HOME)
    hub = TORCH_HOME / 'hub' / 'checkpoints'
    if list(hub.glob('resnet18-*.pth')):
        print('  [ok]   resnet18')
        return True
    if check_only:
        print(f'  [FAIL] resnet18: missing under {hub}')
        return False
    import torchvision
    torchvision.models.resnet18(weights=torchvision.models.ResNet18_Weights.DEFAULT)
    print('  [ok]   resnet18 downloaded')
    return True


def get_roberta(check_only: bool) -> bool:
    os.environ['HF_HOME'] = str(HF_HOME)
    if (HF_HOME / 'hub' / 'models--roberta-base').exists():
        print('  [ok]   roberta-base')
        return True
    if check_only:
        print(f'  [FAIL] roberta-base: missing under {HF_HOME}')
        return False
    from transformers import AutoModel, AutoTokenizer
    AutoTokenizer.from_pretrained('roberta-base')
    AutoModel.from_pretrained('roberta-base')
    print('  [ok]   roberta-base downloaded')
    return True


MODELS = {'resnet18': get_resnet18, 'roberta-base': get_roberta}


def write_env_file() -> Path:
    env = ROOT / 'scripts' / 'env.sh'
    env.write_text(f"""# Generated by scripts/download_models.py. Source before running experiments:
#   source scripts/env.sh
export TORCH_HOME="{TORCH_HOME}"
export HF_HOME="{HF_HOME}"
# Remove the next two lines on a machine with internet access to allow lazy downloads.
export HF_HUB_OFFLINE=1
export TRANSFORMERS_OFFLINE=1
""")
    return env


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true', help='verify only; download nothing')
    p.add_argument('--only', nargs='+', choices=list(MODELS))
    args = p.parse_args()

    results = {}
    for name in args.only or list(MODELS):
        try:
            results[name] = MODELS[name](args.check)
        except Exception as e:
            print(f'  [FAIL] {name}: {type(e).__name__}: {e}')
            results[name] = False
    if not args.check:
        print(f'wrote {write_env_file().relative_to(ROOT)}; run `source scripts/env.sh` before experiments')
    return 0 if all(results.values()) else 1


if __name__ == '__main__':
    sys.exit(main())
